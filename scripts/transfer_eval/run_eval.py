def finish_baseline_view(run: Run, view):
    from rhmp.baselines.registry import SPECS, prepare_task
    view = prepare_task(run.model_name, view, run.build)                      # v1 edge protocol (mpsn / sccnn / clifford)
    if not SPECS[run.model_name].uses_output_map and view.output_map is not None:
        view = dataclasses.replace(view, output_map=None)
    return view


def planar_view(run: Run, cond: PlanarCond, device):
    """View of a planar transfer set for ``run``: RHMP gets the edge cochain (native inputs, oriented face -> node map),
    baselines the legacy node encoding of the edge cochain (normalised with the run's training statistics)."""
    S = cond.E_K.shape[0]
    if run.is_rhmp:
        task = run.task
        x1 = task.x_stats[1].normalize(cond.E_K.to(device))
        y = task.y_stats.normalize(cond.Y.to(device))
        return with_view(task, cond.K, {1: x1.contiguous()}, y.contiguous(), S, output_map=cond.output_map())
    task = run.task_raw
    x0 = task.x_stats[0].normalize(cond.X.to(device))
    y = task.y_stats.normalize(cond.Y.to(device))
    view = with_view(task, cond.K, {0: x0.contiguous()}, y.contiguous(), S, output_map=None)
    return finish_baseline_view(run, view)


def t3_view(run: Run, cond: T3Cond, device):
    S = cond.X.shape[0]
    if run.is_rhmp:
        task = run.task
        x0 = task.x_stats[0].normalize(cond.X.to(device))
        y = task.y_stats.normalize(cond.Y.to(device))
        return with_view(task, cond.K, {0: x0.contiguous()}, y.contiguous(), S, output_map=cond.output_map())
    task = run.task_raw
    x0 = task.x_stats[0].normalize(cond.X.to(device))
    y = task.y_stats.normalize(cond.Y.to(device))
    view = with_view(task, cond.K, {0: x0.contiguous()}, y.contiguous(), S, output_map=None)
    return finish_baseline_view(run, view)


def gauge_theta(K, theta_K: torch.Tensor, s_abs: float, seed: int = GAUGE_SEED) -> torch.Tensor:
    """``theta + d0 lambda`` with ``lambda ~ N(0, s_abs^2)`` per node and sample, drawn as ``rhmp.robustness.gauge_task`` does
    (CPU generator ``manual_seed(seed)``, ``randn((n0, S, 1))``), canonical edges; ``theta_K`` is ``(S, n1, 1)``."""
    g = torch.Generator().manual_seed(seed)
    S = theta_K.shape[0]
    lam = torch.randn((K.n[0], S, 1), generator=g) * s_abs
    e = K.cells[1].long().cpu()
    return theta_K + (lam[e[:, 1]] - lam[e[:, 0]]).permute(1, 0, 2)


def gauge_view(run: Run, cond: PlanarCond, mult: float, rms_theta: float, device, notes: dict):
    """T6 view with the gauge transformation of the stored original test inputs.  RHMP: the library's ``gauge_task`` on the
    loaded task.  Baselines: the same lambda on the raw edge data of the original mesh, legacy node features regenerated
    with the verified formula; the target is the stored one."""
    from rhmp.robustness import gauge_task
    pe = run.task.meta["paper_eval"]
    s_abs = mult * rms_theta
    if run.is_rhmp:
        view = gauge_task(run.task, pe, s_abs, seed=GAUGE_SEED)
        th2 = gauge_theta(cond.K, cond.E_K, s_abs)
        mine = run.task.x_stats[1].normalize(th2.to(device))
        notes["max_abs_diff_inputs_vs_independent_construction"] = float((mine - view.inputs[1]).abs().max())
        return view
    task = run.task_raw
    th2 = gauge_theta(cond.K, cond.E_K, s_abs)
    X2 = encode_edges_to_nodes(th2, cond.edges_K, cond.pts, cond.n0).float()
    x0 = task.x_stats[0].normalize(X2.to(device)).contiguous()
    y = task.target.index_select(0, pe.to(task.target.device))
    view = with_view(task, cond.K, {0: x0}, y.contiguous(), len(pe), output_map=None)
    return finish_baseline_view(run, view)


