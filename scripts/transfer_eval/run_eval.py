def eval_batch_for(run: Run, n0: int) -> int:
    return run.ebs if n0 <= 1500 else 8


def metrics_of(run: Run, view, device, vector: bool, n0: int) -> dict:
    t0 = time.time()
    ebs = eval_batch_for(run, n0)
    while True:                       # the GPU is shared: on a CUDA out-of-memory error halve the (result-neutral) eval batch
        try:
            pred, tgt = predict_view(run, view, device, ebs)
            break
        except torch.cuda.OutOfMemoryError:
            if ebs == 1:
                raise
            torch.cuda.empty_cache()
            ebs = max(1, ebs // 2)
    out = pick(summarize_pred(view, pred, tgt))
    out["eval_batch_used"] = ebs
    if vector and not run.edge_protocol:
        out["R2_iso"] = raw_iso_r2(view, pred, tgt)
    out["finite"] = bool(torch.isfinite(pred).all())
    out["max_abs_pred_normalised"] = float(pred.abs().max())
    out["seconds"] = time.time() - t0
    return out


def evaluate_run(T: str, run: Run, conds: dict, device, conds_wanted: list[str], rms_theta: float) -> dict:
    t0 = time.time()
    task = run.task
    pe = task.meta["paper_eval"]
    vector = T == "T3"
    rec = {"task": T, "model": run.model_name, "run_dir": run.run_dir, "params": run.result.get("params"),
           "train_gpu": run.result.get("gpu"), "stats_rel_diff_loaded_vs_saved": run.stats_rel_diff,
           "target_protocol": (run.result.get("model_info") or {}).get("target_protocol"),
           "eval_batch": run.ebs, "stored_test100": pick(run.result["test100"]), "conditions": {}}
    # ---- the original test100 as the trainer computes it ---------------------------------------------------------------
    if "orig" in conds_wanted:
        m0 = eval_task_samples(run, task, pe, device)
        m0b = eval_task_samples(run, task, pe, device)                         # second pass: noise floor of the device
        rec["recomputed_test100"] = pick(m0)
        keys = ("R2", "SSIM", "Pearson", "NRMSE")
        rec["reproduction_abs_diff"] = {k: abs(rec["recomputed_test100"][k] - rec["stored_test100"][k]) for k in keys}
        rec["reproduction_max_abs_diff"] = max(rec["reproduction_abs_diff"].values())
        rec["repeat_abs_diff"] = max(abs(pick(m0b)[k] - rec["recomputed_test100"][k]) for k in keys)
        from rhmp.train import predict
        with torch.no_grad():
            pred0, tgt0 = predict(run.model, task, pe, run.ebs, device)
        o = pick(summarize_pred(task, pred0, tgt0))
        if vector and not run.edge_protocol:
            o["R2_iso"] = raw_iso_r2(task, pred0, tgt0)
        o["finite"] = bool(torch.isfinite(pred0).all())
        rec["conditions"]["orig"] = o
        del pred0, tgt0
    # ---- the other conditions ----------------------------------------------------------------------------------------
    for cname in conds_wanted:
        if cname == "orig":
            continue
        try:
            notes: dict = {}
            if cname.startswith("gauge_"):
                mult = float(cname.split("_")[1])
                cond = conds["orig_regen"]
                view = gauge_view(run, cond, mult, rms_theta, device, notes)
                n0 = cond.n0
            else:
                cond = conds[cname]
                view = planar_view(run, cond, device) if T in ("T6", "T7") else t3_view(run, cond, device)
                n0 = cond.n0
            m = metrics_of(run, view, device, vector, n0)
            if notes:
                m["notes"] = notes
            rec["conditions"][cname] = m
            del view
        except Exception as e:  # noqa: BLE001 - recorded, the other conditions go on
            traceback.print_exc()
            rec["conditions"][cname] = {"error": repr(e)}
        if device.type == "cuda":
            torch.cuda.empty_cache()
    rec["seconds"] = time.time() - t0
    return rec


def evaluate_run_both(T: str, run: Run, conds: dict, device, conds_wanted: list[str], rms_theta: float) -> dict:
    """``evaluate_run`` with the per-mesh normalisers (default) and, for RHMP runs, again with the normalisers of the
    training mesh (``model.freeze_units(run.task.K)``) under ``rec['frozen_units']`` and with the per-column rule
    ``frozen_descriptors='auto'`` under ``rec['frozen_auto']``."""
    rec = evaluate_run(T, run, conds, device, conds_wanted, rms_theta)
    if run.is_rhmp and hasattr(run.model, "freeze_units"):
        run.model.freeze_units(run.task.K)
        rec["frozen_units"] = evaluate_run(T, run, conds, device, conds_wanted, rms_theta)
        if hasattr(run.model.cfg, "frozen_descriptors"):
            run.model.cfg.frozen_descriptors = "auto"
            rec["frozen_auto"] = evaluate_run(T, run, conds, device, conds_wanted, rms_theta)
    return rec


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tasks", default="T6,T7")
    ap.add_argument("--models", default=None, help="comma-separated subset (default: rhmp + all baselines)")
    ap.add_argument("--conds", default=None, help="comma-separated subset of conditions")
    ap.add_argument("--device", default="cpu")
    ap.add_argument("--tf32", type=int, default=1)
    ap.add_argument("--threads", type=int, default=8)
    ap.add_argument("--mem-fraction", type=float, default=0.035)
    ap.add_argument("--data-dir", default=os.path.join(ROOT, "datasets", "v2", "transfer"))
    ap.add_argument("--out-dir", default=os.path.join(ROOT, "runs", "transfer_eval_out"))
    ap.add_argument("--tag", default=None)
    a = ap.parse_args()
    torch.set_num_threads(a.threads)
    try:
        torch.set_num_interop_threads(1)
    except RuntimeError:
        pass
    device = torch.device(a.device)
    if device.type == "cuda":
        torch.backends.cuda.matmul.allow_tf32 = bool(a.tf32)
        torch.backends.cudnn.allow_tf32 = bool(a.tf32)
        torch.cuda.set_per_process_memory_fraction(a.mem_fraction)
    tag = a.tag or (f"{device.type}_" + ("tf32" if (device.type == "cuda" and a.tf32) else "fp32"))
    os.makedirs(a.out_dir, exist_ok=True)
    warnings.filterwarnings("ignore", message=".*index_reduce.*")
    env = {"device": str(device), "tf32": bool(a.tf32) if device.type == "cuda" else False, "threads": a.threads,
           "torch": torch.__version__, "tag": tag, "gpu": torch.cuda.get_device_name(device) if device.type == "cuda" else "cpu",
           "gauge_mult": GAUGE_MULT, "gauge_seed": GAUGE_SEED}
    print(json.dumps(env), flush=True)
    for T in a.tasks.split(","):
        t_task = time.time()
        spec = SPEC[T]
        wanted = COND_ORDER[T] if a.conds is None else [c for c in COND_ORDER[T] if c in a.conds.split(",")]
        conds, cond_info = {}, {}
        for c in wanted:
            if c == "orig" or c.startswith("gauge_"):
                continue
            path = os.path.join(a.data_dir, f"{T}_{c}.pt")
            conds[c] = PlanarCond(T, c, path, device) if T in ("T6", "T7") else T3Cond(c, path, device)
            cond_info[c] = conds[c].checks
        if T == "T6" and any(c.startswith("gauge_") for c in wanted) and "orig_regen" not in conds:
            conds["orig_regen"] = PlanarCond(T, "orig_regen", os.path.join(a.data_dir, f"{T}_orig_regen.pt"), device)
            cond_info["orig_regen"] = conds["orig_regen"].checks
        print(f"[{T}] conditions built: " + ", ".join(f"{k}: n0={v['n_cells'][0]}" for k, v in cond_info.items()), flush=True)
        rhmp_runs = RHMP_RUNS.get(T, {"rhmp": spec["rhmp"]})
        models = list(rhmp_runs) + [m for m in BASELINES if os.path.isdir(os.path.join(RUNS, spec["base"], f"{m}_s42"))]
        models = [m for m in models if m in (a.models.split(",") if a.models else list(rhmp_runs))]
        res = {"env": env, "task": T, "condition_checks": cond_info, "conditions": wanted, "runs": {}}
        path = os.path.join(a.out_dir, f"results_{T}_{tag}.json")
        cache: dict = {}
        rms_theta = None
        for m in models:
            rdir = os.path.join(RUNS, rhmp_runs[m] if m in rhmp_runs else os.path.join(spec["base"], f"{m}_s42"))
            try:
                run = load_run(rdir, T, "rhmp" if m in rhmp_runs else m, device, cache)
                if T == "T6" and m == "rhmp":
                    rms_theta = float(run.task.x_stats[1].std[0])
                    res["rms_theta_training"] = rms_theta
                rec = evaluate_run_both(T, run, conds, device, wanted,
                                        rms_theta if rms_theta is not None else 0.2891596555709839)
                res["runs"][m] = rec
                r2 = {k: round(v.get("R2", float("nan")), 4) for k, v in rec["conditions"].items()}
                rep = rec.get("reproduction_max_abs_diff")
                print(f"[{T}/{m}] stored R2 {rec['stored_test100']['R2']:.5f} repro {rep if rep is None else format(rep, '.1e')} "
                      f"R2={r2} [{rec['seconds']:.0f}s]", flush=True)
                for mode in ("frozen_units", "frozen_auto"):
                    if mode in rec:
                        r2f = {k: round(v.get("R2", float("nan")), 4) for k, v in rec[mode]["conditions"].items()}
                        print(f"[{T}/{m}] {mode} R2={r2f}", flush=True)
                del run
            except Exception as e:  # noqa: BLE001
                traceback.print_exc()
                res["runs"][m] = {"task": T, "model": m, "error": repr(e)}
            json.dump(jsonable(res), open(path, "w"), indent=1)
            if device.type == "cuda":
                torch.cuda.empty_cache()
        res["seconds"] = time.time() - t_task
        json.dump(jsonable(res), open(path, "w"), indent=1)
        print(f"[{T}] done in {res['seconds']:.0f}s -> {path}", flush=True)


if __name__ == "__main__":
    main()
