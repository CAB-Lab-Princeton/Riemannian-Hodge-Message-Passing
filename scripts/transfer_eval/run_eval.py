"""Zero-shot transfer of the trained runs (no training): test100 metrics on new meshes, new geometries, gauge transforms.

Reproduces the zero-shot gauge-field table of the paper (``results/evaluations/wilson_loop_zero_shot.json``,
``yang_mills_zero_shot.json``).  Every condition is scored with the per-mesh normalisers of each mesh (``default``),
with those of the training mesh (``frozen_units``: ``model.freeze_units(K_train)`` on the trained checkpoint, no
retraining) and with the per-column rule ``frozen_descriptors='auto'`` (``frozen_auto``).

    python3 scripts/transfer_eval/gen_planar.py --task T6          # once: the test data of the conditions (GPU)
    python3 scripts/transfer_eval/gen_planar.py --task T7
    cd scripts/transfer_eval && CUDA_VISIBLE_DEVICES=0 python3 run_eval.py --device cuda --tf32 1 --tasks T6,T7 --models rhmp
    CUDA_VISIBLE_DEVICES=  python3 run_eval.py --device cpu  --tasks T6,T7 --tag cpu_fp32     # all runs, CPU

Runs (read only): ``results/<task>/rhmp_s42`` (RHMP, native cochain inputs) and ``results/<task>/<model>_s42`` (the
baselines, legacy node-encoded inputs; mpsn / sccnn / clifford_smpn scored in edge space as their runs were), see
``tc_common.SPEC`` (``RHMP_RUNS`` selects another run root).  Test data of the conditions: ``gen_planar.py`` (T6, T7),
written to ``datasets/v2/transfer``.  Per condition the library metrics (``rhmp.metrics.summarize`` on the predictions of ``rhmp.train.predict``) on
the 100 test samples, in the normalisation of the training run (statistics of the original training split, never recomputed).

Conditions
  ``orig``        the stored original test100 (library loader), must reproduce ``result.json["test100"]``;
  ``orig_regen``  the original mesh with fields / inputs / targets regenerated by this pipeline (verification);
  T6 / T7: ``new`` (other random Delaunay mesh, 1024 nodes), ``aniso`` (3:1 anisotropic triangulation), ``fine`` (4096 nodes);
  T6:      ``gauge_<m>``  original data with ``theta -> theta + d0 lambda``, ``lambda ~ N(0, (m rms)^2)`` per node and sample,
           m = 0.1, 1, 10 (rms = training rms of theta), the curvature target unchanged;
  T3:      ``fine`` / ``coarse2`` / ``coarse`` (same ellipsoid, 4625 / 577 / 290 nodes), ``elong``, ``triax`` (other ellipsoids).
"""
from __future__ import annotations

import argparse
import dataclasses
import json
import os
import time
import traceback
import warnings

import numpy as np
import torch

from tc_common import (BASELINES, RHMP_RUNS, ROOT, RUNS, SPEC, Run, encode_edges_to_nodes, eval_task_samples, jsonable,
                       load_run, pick, predict_view, raw_iso_r2, summarize_pred, with_view)

GAUGE_MULT = (0.1, 1.0, 10.0)
GAUGE_SEED = 0
SUPP = ["new_s1", "aniso_s1", "new_s2", "aniso_s2", "new_s3", "aniso_s3", "graded"]   # supplementary meshes
COND_ORDER = {
    "T6": ["orig", "orig_regen", "new", "aniso", "fine", "gauge_0.1", "gauge_1", "gauge_10"] + SUPP,
    "T7": ["orig", "orig_regen", "new", "aniso", "fine"] + SUPP,
    "T3": ["orig", "orig_regen", "fine", "coarse2", "coarse", "elong", "triax"],
}


def make_complex(pts, faces, device):
    """Complex of a mesh exactly as the task loaders build it (``rhmp.tasks.paper._complex``, cotan star)."""
    from rhmp.data import strip_whitney
    from rhmp.tasks.paper import _complex
    K = _complex(np.asarray(pts, dtype=np.float64), np.asarray(faces, dtype=np.int64), "cotan", device)
    strip_whitney(K)
    return K


