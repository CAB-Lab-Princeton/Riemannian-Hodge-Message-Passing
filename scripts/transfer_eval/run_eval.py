class PlanarCond:
    """T6 / T7 transfer set: complex, edge cochain in the complex's edge order / orientation, legacy node inputs, targets."""

    def __init__(self, T: str, name: str, path: str, device):
        from rhmp.data import cell_alignment, edge_alignment
        from rhmp.tasks.paper import oriented_face_to_node
        d = torch.load(path, map_location="cpu", weights_only=False)
        self.T, self.name, self.device = T, name, device
        self.c = 1 if T == "T6" else 3
        self.pts = d["pts"].numpy()
        self.faces = d["faces"].numpy()
        self.n0 = len(self.pts)
        self.K = make_complex(self.pts, self.faces, device)
        K = self.K
        self.n1, self.n2 = K.n[1], K.n[2]
        E = d["theta"].unsqueeze(-1) if T == "T6" else d["A"]
        F = d["plaq"].unsqueeze(-1) if T == "T6" else d["F"]
        perm, sign = edge_alignment(K.cells[1], d["edges"], self.n0)
        self.edge_order_identical = bool(torch.equal(perm, torch.arange(len(perm))) and bool((sign == 1).all()))
        self.E_K = (E[:, perm] * sign[None, :, None]).contiguous()
        fperm, fsign = cell_alignment(K.cells[2], d["faces"], self.n0)
        self.face_order_identical = bool(torch.equal(fperm, torch.arange(len(fperm))) and bool((fsign == 1).all()))
        self.F_K = (F[:, fperm] * fsign[None, :, None]).contiguous()
        self.X, self.Y = d["X"].contiguous(), d["Y"].contiguous()
        self.edges_K = K.cells[1].long().cpu().numpy()
        # consistency of the data with the library's complex (K orientation)
        om = oriented_face_to_node(K, self.c)
        S = min(16, E.shape[0])
        th = self.E_K[:S].permute(1, 0, 2).contiguous().to(device)
        dth = K.apply_d(1, th).permute(1, 0, 2).cpu()
        ref_face = self.F_K[:S] if T == "T6" else (d["dA"][:S][:, fperm] * fsign[None, :, None])
        Yom = om(self.F_K[:S].permute(1, 0, 2).contiguous().to(device)).permute(1, 0, 2).cpu()
        self.checks = {"max_abs_d1_edge_cochain_minus_face_cochain": float((dth - ref_face).abs().max()),
                       "max_abs_face_cochain": float(ref_face.abs().max()),
                       "max_abs_oriented_face_to_node_of_face_cochain_minus_target": float((Yom - self.Y[:S]).abs().max()),
                       "edge_order_identical_to_canonical": self.edge_order_identical,
                       "face_order_identical_to_input": self.face_order_identical,
                       "n_cells": [self.n0, self.n1, self.n2], "faces_dropped_by_complex": int(len(self.faces) - self.n2)}
        self._om = om

    def output_map(self):
        return self._om


class T3Cond:
    """T3 transfer set: complex (built from the float32 points as the loader does), stream functions, targets."""

    def __init__(self, name: str, path: str, device):
        d = torch.load(path, map_location="cpu", weights_only=False)
        self.name, self.device = name, device
        self.faces = d["faces"].numpy()
        self.pts_loader = d["pts32"].numpy().astype(np.float64)          # the loader reads the float32 points as float64
        self.n0 = len(self.pts_loader)
        self.K = make_complex(self.pts_loader, self.faces, device)
        self.n1, self.n2 = self.K.n[1], self.K.n[2]
        self.X, self.Y = d["X"].contiguous(), d["Y"].contiguous()
        self.checks = {"n_cells": [self.n0, self.n1, self.n2], "faces_dropped_by_complex": int(len(self.faces) - self.n2)}
        self._om = None

    def output_map(self):
        if self._om is None:
            from rhmp.tasks.paper import surface_rotation
            self._om = surface_rotation(self.K, self.faces, self.pts_loader)
        return self._om


