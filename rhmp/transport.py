"""Transport term: discrete Lie derivative of the vertex features along edge transport fields (``RHMPConfig.transport``).

Scalar transport ``d_t u + div(u v) = 0`` is generated by an operator that is not symmetric, so the symmetric positive
semi-definite Hodge blocks of the layer cannot represent it; without this term a model can only get a direction from
learned latent fields through the cross terms.  The transport term adds, on the vertices, the dual-cell flux balance
of the features along one or more *transport fields*.

A transport field ``phi`` is an odd (orientation-reversing), channel-invariant edge scalar: a velocity one-form given
as an input column of degree 1 (``'inputs'``), a latent edge column (``'latent'``), or an O(C)-invariant odd
contraction of the hidden state (``'hidden'``).  With the metric ``H_1`` of the layer (the one the up block of degree
0 uses) it defines the flux through the dual edges and three operators on the vertex features (symmetrised DEC frame
``x = star_0^{1/2} u``, ``s = star_0^{-1/2}`` the scaling of the degree-0 up block)::

    F      = (H_1 phi) / beta_up0                              flux through the dual edges (normalised metric)
    C(F) x = s ⊙ d_0^T ( F ⊙ |d_0| (s ⊙ x) ) / 2                conservative, centred: dual-cell flux balance
    A(F) x = s ⊙ |d_0|^T ( F ⊙ d_0 (s ⊙ x) ) / 2                advective, centred (A = C^T)
    U(F) x = s ⊙ d_0^T ( |F| ⊙ d_0 (s ⊙ x) ) / 2                upwind correction (graph Laplacian, weights |F| / 2)

The conservative upwind flux is ``C - U`` and the advective upwind form ``A + U``.  With the reference metric
``H_1 = star_1`` (cotan weights) ``star_1 phi`` is the DEC flux of ``v`` through the dual edges, ``C`` is the
finite-volume discretisation of ``-div(u v)`` on the dual cells and ``A`` that of ``v . grad u`` (both times the dual
area, mapped to the symmetric frame).  The message of degree 0 gains

    T   = sum_j ( a_j C(F_j) + b_j A(F_j) + c_j U(F_j) )           scalar coefficients per layer and field (init 0)
    m_0 += sum_{p=1..P} g_p T^p x_0,      g_1 = 1,  g_{p>1} learned (init 0)

Properties (tests in ``tests/test_transport.py``):

* the operator is linear in the hidden state and acts identically on every channel: O(C)-equivariant;
* ``phi`` odd and ``d_0`` odd: ``C``, ``A``, ``U`` are invariant under edge-orientation changes and vertex relabelling;
  only metrics, stars and incidence enter (E(n)-invariant);
* ``C`` and ``U`` conserve ``sum_i star_i^{1/2} x_i = sum_i star_i u_i`` exactly (``1^T d_0^T = 0``); ``A`` does not
  (it differs from ``-C`` by the divergence of the flux, ``C + A = diag(d_0^T F)`` in the physical frame);
* for a divergence-free flux (``d_0^T F = 0``) ``C`` is skew-symmetric (energy conserving);
* ``metric='star'`` replaces the learned ``H_1`` by the reference star ``star_1`` (the geometric DEC flux; for models
  whose learned metric carries a material such as an anisotropic diffusion tensor, which must not weight advection);
* norm bounds: ``||C(F)||, ||A(F)||, ||U(F)|| <= max_e |phi_e| / 2`` per sample (``norm='metric'``: the metric is
  normalised by the Gershgorin bound of the degree-0 up block, the field keeps its magnitude, which is the transport
  speed); ``norm='sample'`` divides every field operator by its own per-sample Gershgorin bound (``<= 1``, and
  invariant to the magnitude of the field).  Hidden-state fields pass through ``tanh`` (bounded, odd).

Other degrees: hidden cochains of degree ``k >= 1`` are orientation-odd, so an unsigned interpolation ``|d_k| x_k`` is
not a cochain and the construction above is specific to the (even) vertex features.  The transport of k-forms
(``L_v = d i_v + i_v d``) needs a discrete interior product with the flux (twisted) form of ``v``, which an edge
circulation does not determine; it is not implemented.
"""
from __future__ import annotations

from typing import Any

import torch
from torch import Tensor, nn

from . import ops

__all__ = ["TRANSPORT_FORMS", "TRANSPORT_NORMS", "TRANSPORT_METRICS", "TRANSPORT_HIDDEN_MAX", "normalize_transport",
           "TransportTerm", "transport_columns", "transport_weights", "apply_transport", "transport_bound"]

TRANSPORT_FORMS = ("cons", "adv", "upwind")
TRANSPORT_NORMS = ("metric", "sample")
# hidden-state fields: 1 = <x_1, (|d_0| x_0) / 2> / C, 2 = also d_0 (|x_0|^2 / (2 C)) (both odd and O(C)-invariant)
TRANSPORT_HIDDEN_MAX = 2
TRANSPORT_METRICS = ("layer", "star")
_KEYS = ("inputs", "latent", "hidden", "forms", "order", "norm", "metric")


def normalize_transport(spec: Any) -> dict:
    """Validated transport specification with defaults, or ``{}`` (transport off).

    Keys: ``inputs`` (list of odd column indices of ``inputs[1]``, default ``[]``), ``latent`` (number of latent edge
    columns used as fields, the first ones of ``latent_dims[1]``, default 0), ``hidden`` (0, 1 or 2 hidden-state
    fields, default 0), ``forms`` (subset of ``('cons', 'adv', 'upwind')``, default all), ``order`` (``P >= 1``,
    default 1), ``norm`` (``'metric'`` (default) or ``'sample'``), ``metric`` (``'layer'`` (default): the layer's
    learned edge metric ``H_1``; ``'star'``: the reference star ``star_1``, i.e. the geometric DEC flux, for models
    whose learned metric carries a material such as an anisotropic diffusion tensor).

    Raises:
        ValueError: on unknown keys or invalid values, or if no field is selected.
    """
    if not spec:
        return {}
    spec = dict(spec)
    bad = set(spec) - set(_KEYS)
    if bad:
        raise ValueError(f"transport: unknown keys {sorted(bad)}; known: {list(_KEYS)}")
    out = dict(inputs=[int(c) for c in spec.get("inputs", []) or []], latent=int(spec.get("latent", 0) or 0),
               hidden=int(spec.get("hidden", 0) or 0), forms=list(spec.get("forms", TRANSPORT_FORMS)),
               order=int(spec.get("order", 1)), norm=str(spec.get("norm", "metric")),
               metric=str(spec.get("metric", "layer")))
    if isinstance(spec.get("forms"), str):
        out["forms"] = [f for f in spec["forms"].replace("+", ",").split(",") if f]
    if len(set(out["inputs"])) != len(out["inputs"]) or any(c < 0 for c in out["inputs"]):
        raise ValueError(f"transport['inputs'] must be distinct non-negative column indices, got {out['inputs']}")
    if out["latent"] < 0 or not 0 <= out["hidden"] <= TRANSPORT_HIDDEN_MAX:
        raise ValueError(f"transport: need latent >= 0 and 0 <= hidden <= {TRANSPORT_HIDDEN_MAX}")
    if not out["forms"] or any(f not in TRANSPORT_FORMS for f in out["forms"]) or \
            len(set(out["forms"])) != len(out["forms"]):
        raise ValueError(f"transport['forms'] must be a non-empty subset of {TRANSPORT_FORMS}, got {out['forms']}")
    out["forms"] = [f for f in TRANSPORT_FORMS if f in out["forms"]]
    if out["order"] < 1:
        raise ValueError("transport['order'] must be >= 1")
    if out["norm"] not in TRANSPORT_NORMS:
        raise ValueError(f"transport['norm'] must be one of {TRANSPORT_NORMS}, got {out['norm']!r}")
    if out["metric"] not in TRANSPORT_METRICS:
        raise ValueError(f"transport['metric'] must be one of {TRANSPORT_METRICS}, got {out['metric']!r}")
    if not (out["inputs"] or out["latent"] or out["hidden"]):
        raise ValueError("transport: select at least one field ('inputs', 'latent' or 'hidden')")
    return out


def transport_columns(cfg: Any) -> list[int]:
    """Columns of the effective ``inputs[1]`` (latent columns inserted, layout ``[connection | odd | latent | even]``)
    that are transport fields: the requested odd input columns, then the first ``transport['latent']`` latent columns.

    Raises:
        ValueError: if a requested column is not an ordinary odd column (connection and even columns cannot carry a
            transport field: a connection would break the gauge invariance, an even column the orientation parity).
    """
    t = normalize_transport(getattr(cfg, "transport", None))
    if not t:
        return []
    F = int(cfg.in_dims.get(1, 0))
    E = int(cfg.even_dims.get(1, 0))
    c = int(cfg.connection_dims.get(1, 0))
    for col in t["inputs"]:
        if not c <= col < F - E:
            raise ValueError(f"transport['inputs']: column {col} of inputs[1] is not an ordinary odd column "
                             f"(odd columns: {list(range(c, F - E))})")
    r = int(cfg.latent_dims.get(1, 0))
    if t["latent"] > r:
        raise ValueError(f"transport['latent'] = {t['latent']} exceeds latent_dims[1] = {r}")
    return list(t["inputs"]) + [F - E + i for i in range(t["latent"])]


def transport_bound(g: Any, absF: Tensor) -> Tensor:
    """Per-cell Gershgorin row bounds of ``C(F)``, ``A(F)`` and ``U(F)``: ``s_i [ |d_0|^T (|F| ⊙ |d_0| s) ]_i / 2``.

    Args:
        g: the ``BlockGeometry`` of the degree-0 up block (scaling folded into ``A_abs``, ``AT_abs``; ``g.r = |d_0| s``).
        absF: ``|F|`` ``(n_1, B, J)``.

    Returns:
        ``(n_0, B, J)``; the row sums and the column sums of ``|C|``, ``|A|``, ``|U|`` are bounded by these values.
    """
    return 0.5 * ops.spmm(g.AT_abs, (absF * g.r).contiguous())


def transport_weights(F: Tensor, coef: dict[str, Tensor]) -> dict[str, Tensor]:
    """Edge weights of ``T = sum_j a_j C(F_j) + b_j A(F_j) + c_j U(F_j)``: ``{'cons': (n1, B, 1), ...}``.

    Args:
        F: fluxes ``(n_1, B, J)``.
        coef: ``{form: (J,)}`` coefficients (``a`` for ``'cons'``, ``b`` for ``'adv'``, ``c`` for ``'upwind'``).
    """
    out = {}
    for form, w in coef.items():
        src = F.abs() if form == "upwind" else F
        out[form] = 0.5 * (src * w.to(src.dtype)).sum(-1, keepdim=True)
    return out


def apply_transport(g: Any, w: dict[str, Tensor], x: Tensor, q: Tensor | None = None) -> Tensor:
    """``T x`` for the edge weights ``w`` (:func:`transport_weights`): ``(n_0, B, C) -> (n_0, B, C)``.

    ``C x = AT (w_C ⊙ A_abs x)``, ``U x = AT (w_U ⊙ A x)``, ``A x = AT_abs (w_A ⊙ A x)`` with the scaled operators of
    the degree-0 up block (``A = d_0 diag(s)``, ``AT = diag(s) d_0^T``, absolute values likewise).

    Args:
        g: ``BlockGeometry`` of the degree-0 up block.
        w: edge weights (missing forms are skipped).
        x: vertex features.
        q: optional precomputed ``A x`` (shared first coboundary of the layer).
    """
    from .layers import spmm_ad
    out = None
    need_q = "adv" in w or "upwind" in w
    if need_q and q is None:
        q = spmm_ad(g.A, g.AT, x)
    z = None
    if "cons" in w:
        z = w["cons"] * spmm_ad(g.A_abs, g.AT_abs, x)
    if "upwind" in w:
        z = w["upwind"] * q if z is None else z + w["upwind"] * q
    if z is not None:
        out = spmm_ad(g.AT, g.A, z)
    if "adv" in w:
        t = spmm_ad(g.AT_abs, g.A_abs, w["adv"] * q)
        out = t if out is None else out + t
    return out


class TransportTerm(nn.Module):
    """Transport term of one layer (see the module docstring).

    Args:
        spec: transport specification (:func:`normalize_transport`; non-empty).  The input and latent fields are read
            from ``ctx.transport_fields`` (``(n_1, B, len(inputs) + latent)``, set by the model from the columns
            :func:`transport_columns`), the hidden fields are computed from the layer input.
    """

    def __init__(self, spec: dict) -> None:
        super().__init__()
        spec = normalize_transport(spec)
        if not spec:
            raise ValueError("TransportTerm needs a non-empty transport specification")
        self.spec = spec
        self.n_input = len(spec["inputs"]) + int(spec["latent"])
        self.n_hidden = int(spec["hidden"])
        self.J = self.n_input + self.n_hidden
        if self.J < 1:
            raise ValueError("TransportTerm: no transport field")
        self.order = int(spec["order"])
        self.norm = spec["norm"]
        self.coef = nn.ParameterDict({f: nn.Parameter(torch.zeros(self.J)) for f in spec["forms"]})
        self.gamma = nn.Parameter(torch.zeros(self.order - 1)) if self.order > 1 else None

    def extra_repr(self) -> str:
        return (f"fields={self.J} (inputs/latent {self.n_input}, hidden {self.n_hidden}), forms={self.spec['forms']}, "
                f"order={self.order}, norm={self.norm}, metric={self.spec['metric']}")

    def fields(self, x: list[Tensor], ctx: Any) -> Tensor:
        """Transport fields ``phi`` ``(n_1, B, J)``: input / latent columns (``ctx.transport_fields``), then the hidden
        fields ``tanh(<x_1, (|d_0| x_0) / 2> / C)`` and ``tanh(d_0 (|x_0|^2 / (2 C)))``."""
        from .layers import mean_square, spmm_ad
        K = ctx.K
        parts = []
        if self.n_input:
            tf = getattr(ctx, "transport_fields", None)
            if tf is None or tf.shape[-1] != self.n_input:
                got = None if tf is None else tuple(tf.shape)
                raise ValueError(f"transport: expected {self.n_input} input fields in the context, got {got}")
            parts.append(tf.to(x[0].dtype).expand(-1, x[0].shape[1], -1))
        if self.n_hidden >= 1:
            avg = 0.5 * spmm_ad(K.d_abs[0], K.dT_abs[0], x[0])                         # (x_src + x_dst) / 2
            parts.append(torch.tanh(torch.linalg.vecdot(x[1], avg) / x[1].shape[-1]).unsqueeze(-1))
        if self.n_hidden >= 2:
            e = (0.5 * mean_square(x[0])).unsqueeze(-1).contiguous()                  # |x_0|^2 / (2 C)
            parts.append(torch.tanh(spmm_ad(K.d[0], K.dT[0], e)))
        return torch.cat(parts, -1) if len(parts) > 1 else parts[0]

    def fluxes(self, phi: Tensor, ctx: Any, logH1: Tensor | None, tm: Any = None) -> Tensor:
        """``F = (H_1 phi) / beta_up0`` ``(n_1, B, J)``; ``norm='sample'`` further divides every field by the
        per-sample Gershgorin bound of its operators."""
        from .layers import block_operands, tensor_operands
        if self.spec["metric"] == "star":                                     # geometric flux star_1 phi
            logH1, tm = ctx.log_star[1].unsqueeze(1).expand(-1, phi.shape[1]), None
        if tm is not None:                                                    # Whitney tensor metric on the edges
            op = tensor_operands(ctx, 0, tm)
            F = tm.apply(phi.contiguous()) * op.inv_beta
        else:
            op = block_operands(ctx, 0, True, logH1)
            F = torch.exp(op.log_h).unsqueeze(-1) * phi
        if self.norm == "sample":
            g = ctx.blocks[(0, True)]
            rb = transport_bound(g, F.abs())                                  # (n_0, B, J)
            n0, B, J = rb.shape
            beta = ctx.cell_max(rb.reshape(n0, B * J), 0).reshape(-1, B, J)    # (1|G, B, J)
            beta = torch.where(beta > 0, beta, torch.ones_like(beta))
            F = F / (beta if ctx.batch is None else beta[ctx.batch[1]])
        return F

    def forward(self, x: list[Tensor], ctx: Any, logH1: Tensor | None, tm: Any = None,
                q: Tensor | None = None, diag: dict | None = None) -> Tensor:
        """Transport message of the vertices ``sum_p g_p T^p x_0`` ``(n_0, B, C)``.

        Args:
            x: layer input features.
            ctx: forward context (``scaling`` ``'dec'`` or ``'none'``).
            logH1: ``log H_1`` of the degree-0 up block ``(n_1, B)`` (diagonal metric), or ``None`` with ``tm``.
            tm: Whitney tensor metric of degree 1 (``rhmp.layers.TensorMetric``), or ``None``.
            q: optional shared first coboundary ``(d_0 diag(s)) x_0``.
            diag: optional dict receiving scalar diagnostics (``transport_absF_max``, ``transport_<form>_absmax``).
        """
        if ctx.scaling == "jacobi":
            raise ValueError("the transport term needs scaling 'dec' or 'none'")
        F = self.fluxes(self.fields(x, ctx), ctx, logH1, tm)
        w = transport_weights(F, dict(self.coef.items()))
        g = ctx.blocks[(0, True)]
        y = apply_transport(g, w, x[0], q)
        out = y
        for p in range(1, self.order):
            y = apply_transport(g, w, y.contiguous())
            out = out + self.gamma[p - 1] * y
        if diag is not None:
            diag["transport_absF_max"] = F.detach().abs().amax().float()
            for f, c in self.coef.items():
                diag[f"transport_{f}_absmax"] = c.detach().abs().amax().float()
        return out
